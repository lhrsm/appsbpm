export const buscarArtigos = (
  termo: string,
  filtros: { modulo?: string; perfil?: string; nivel?: string; situacao?: string },
) => {
  const t = termo.trim().toLowerCase();
  return ARTIGOS.filter((a) => {
    if (filtros.modulo && filtros.modulo !== "todos" && a.modulo !== filtros.modulo) return false;
    if (filtros.perfil && filtros.perfil !== "todos" && a.perfil !== filtros.perfil && a.perfil !== "Todos os perfis") return false;
    if (filtros.nivel && filtros.nivel !== "todos" && a.nivel !== filtros.nivel) return false;
    if (filtros.situacao && filtros.situacao !== "todos" && a.situacao !== filtros.situacao) return false;
    if (!t) return true;
    const alvo = [
      a.titulo,
      a.resumo,
      a.categoria,
      a.perfil,
      MODULO_LABEL[a.modulo] ?? a.modulo,
      a.palavras.join(" "),
      a.nota ?? "",
      (a.passos ?? []).map((p) => `${p.titulo} ${p.descricao}`).join(" "),
    ]
      .join(" ")
      .toLowerCase();
    return t.split(/\s+/).every((w) => alvo.includes(w));
  });
};
